"""Export the actual assembly bytes and symbol offsets as Rocq definitions."""
from dataclasses import dataclass
from pathlib import Path
import re
import subprocess
import sys
import tempfile


@dataclass(frozen=True)
class Instruction:
    offset: int
    encoding: bytes
    mnemonic: str


@dataclass(frozen=True)
class Program:
    code: bytes
    instructions: tuple[Instruction, ...]
    labels: tuple[tuple[str, int], ...]


def run(*arguments):
    return subprocess.run(arguments, check=True, text=True,
                          stdout=subprocess.PIPE).stdout


def inspect_object(object_file):
    with tempfile.TemporaryDirectory(prefix='x86-bytes-') as temporary:
        binary = Path(temporary) / 'text.bin'
        run('llvm-objcopy', '--dump-section', f'.text={binary}', str(object_file))
        code = binary.read_bytes()
    relocations = run('llvm-readobj', '--relocations', str(object_file))
    if re.search(r'\bR_X86_64_', relocations):
        raise ValueError('the object contains relocations')
    listing = run('llvm-objdump', '-d', '--x86-asm-syntax=intel', str(object_file))
    pattern = r'^\s*([0-9a-f]+):\s+((?:[0-9a-f]{2}\s+)+)([a-z][a-z0-9]*)\b'
    instructions = tuple(
        Instruction(int(match[1], 16), bytes.fromhex(match[2]), match[3])
        for line in listing.splitlines()
        if (match := re.match(pattern, line)))
    offset = 0
    for instruction in instructions:
        encoding = instruction.encoding
        if instruction.offset != offset or code[offset:offset + len(encoding)] != encoding:
            raise ValueError('disassembly does not cover consecutive object bytes')
        if not 1 <= len(encoding) <= 15:
            raise ValueError('instruction length is outside the x86 limit')
        offset += len(encoding)
    if not instructions or offset != len(code):
        raise ValueError('disassembly does not cover the text section')
    symbols = run('llvm-nm', '--numeric-sort', str(object_file))
    labels = tuple(
        (match[2][2:], int(match[1], 16))
        for line in symbols.splitlines()
        if (match := re.fullmatch(r'([0-9a-f]+) t (\.L[a-zA-Z0-9_]+)', line)))
    if ('entry', 0) not in labels or ('cleanup', instructions[-6].offset) not in labels:
        raise ValueError('missing assembly labels; assemble with clang -Wa,-L')
    boundaries = {instruction.offset for instruction in instructions}
    if any(offset not in boundaries for _, offset in labels):
        raise ValueError('a label is not at an instruction boundary')
    if len({name for name, _ in labels}) != len(labels):
        raise ValueError('duplicate label name')
    return Program(code, instructions, labels)


def rocq_source(program):
    byte_lines = ['    ' + '; '.join(str(byte) for byte in program.code[i:i + 16])
                  for i in range(0, len(program.code), 16)]
    instruction_lines = [
        f'    ({instruction.offset}, {len(instruction.encoding)})'
        f' (* {instruction.mnemonic} *)'
        for instruction in program.instructions]
    labels = '\n'.join(f'Definition offset_{name} : Z := {offset}.'
                       for name, offset in program.labels)
    label_values = '; '.join(f'offset_{name}' for name, _ in program.labels)
    return f'''(* SPDX-License-Identifier: GPL-3.0-or-later *)
(* Generated by generate_program.py from permute.o. Do not edit.
   Bytes come from .text; offsets and lengths come from llvm-objdump.
   The structural lemmas below do not establish decoder correctness. *)
From Stdlib Require Import List ZArith.
From ASCommon Require Import Common.
Import ListNotations.
Open Scope Z_scope.

Definition program_bytes : list (bv 8) := map (Z_to_bv 8) [
{';\n'.join(byte_lines)}
  ].

Definition program_instructions : list (Z * Z) := [
{';\n'.join(instruction_lines)}
  ].

{labels}

Definition program_label_offsets : list Z := [{label_values}].

Lemma program_size : List.length program_bytes = {len(program.code)}%nat.
Proof. reflexivity. Qed.

Lemma instruction_count : List.length program_instructions = {len(program.instructions)}%nat.
Proof. reflexivity. Qed.

Lemma instruction_lengths :
  forallb (fun item => (1 <=? snd item) && (snd item <=? 15))
    program_instructions = true.
Proof. vm_compute. reflexivity. Qed.

Lemma instruction_bytes_cover :
  List.concat (map (fun item =>
    firstn (Z.to_nat (snd item))
      (skipn (Z.to_nat (fst item)) program_bytes)) program_instructions) =
    program_bytes.
Proof. vm_compute. reflexivity. Qed.

Lemma labels_are_instruction_boundaries :
  forallb (fun offset => existsb (fun item => Z.eqb offset (fst item))
    program_instructions) program_label_offsets = true.
Proof. vm_compute. reflexivity. Qed.
'''


def main(object_file, destination):
    program = inspect_object(object_file)
    destination.write_text(rocq_source(program))
    print(f'{len(program.code)} bytes, {len(program.instructions)} instructions, '
          f'{len(program.labels)} labels exported to {destination}')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit('usage: generate_program.py ASSEMBLY_OBJECT X86Program.v')
    main(*(Path(argument).resolve() for argument in sys.argv[1:]))
