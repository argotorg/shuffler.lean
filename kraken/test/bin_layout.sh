#!/usr/bin/env bash
# Make BbuKraken/BinLayout.lean, the start address and the byte size of each
# directive of `bbuAsm` in build/kraken/c/bbu_harness.
# With --check, do not write the file, but fail if it is not current.
#
# A label has size 0. An instruction has the size of its bytes in the binary plus
# the size of the alignment nops that follow it: the Kraken parser drops `.p2align`,
# so the padding has no directive of its own.
set -euo pipefail
dir=$(cd "$(dirname "$0")/.." && pwd)
root=$(cd "$dir/.." && pwd)
out=BbuKraken/BinLayout.lean
bin=$root/build/kraken/c/bbu_harness
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

cmake -S "$root" -B "$root/build" -G Ninja -DBUILD_TESTING=ON >/dev/null
cmake --build "$root/build" --target shuffler_bbu_harness >/dev/null
(cd "$root" && lake build -q BbuKraken.Asm Kraken.X64.PrintATT >/dev/null)
(cd "$root" && lake env lean --run kraken/test/BinAsmMain.lean) > "$tmp/asm"
"$dir/test/bin_objdump.sh" "$bin" > "$tmp/dis"

awk -v src="build/kraken/c/bbu_harness" '
	function labelcode(s,   h, i) {
		h = 0
		for (i = 1; i <= length(s); i++) h = (h * 257 + code[substr(s, i, 1)]) % 4294967296
		return h
	}
	BEGIN { for (i = 1; i < 128; i++) code[sprintf("%c", i)] = i }
	FNR == 1 { file++ }
	# The Kraken program: a label ends with ":", all else is an instruction.
	file == 1 {
		kind[nk++] = /:$/ ? "label" : "instr"
		if (/:$/) labels[nlabels++] = substr($0, 1, length($0) - 1)
		else ni++
		next
	}
	# The disassembly: "start ADDR", "stop ADDR", then "ADDR SIZE pad|instr TEXT".
	$1 == "start" { start = $2; next }
	$1 == "stop" { stop = $2; next }
	$1 == "external" && $2 == "exit" { exitaddr = $3; next }
	$3 == "instr" { addr[na++] = strtonum("0x" $1) }
	END {
		if (exitaddr == "" || strtonum("0x" exitaddr) >= strtonum("0x" start)) {
			print "bin_layout: exit@plt must be below the shuffler code" > "/dev/stderr"
			exit 1
		}
		if (na != ni) {
			printf "bin_layout: %d instructions in Kraken, %d in %s\n", ni, na, src > "/dev/stderr"
			exit 1
		}
		if (addr[0] != strtonum("0x" start)) {
			print "bin_layout: the first instruction is not at the start" > "/dev/stderr"
			exit 1
		}
		addr[na] = strtonum("0x" stop)
		print "module"
		print ""
		print "@[expose] public section"
		print ""
		print "/-! Generated by test/bin_layout.sh from " src ". Do not edit. -/"
		print ""
		print "namespace Bbu.BinLayout"
		print ""
		print "/-- The address of the first directive. -/"
		print "def start : Nat := 0x" start
		print ""
		print "/-- The external exit entry in the procedure linkage table. -/"
		print "def exit : Nat := 0x" exitaddr
		print ""
		print "/-- The labels, in directive order, with the external exit entry first. -/"
		print "def labels : List String := [\"exit\","
		for (i = 0; i < nlabels; i++)
			printf "  \"%s\"%s\n", labels[i], (i + 1 < nlabels ? "," : "]")
		print ""
		print "/-- Codes used for the label distinctness check. Lean checks each code. -/"
		printf "def labelCodes : List Nat := [%.0f", labelcode("exit")
		for (i = 0; i < nlabels; i++) printf ",%s%.0f", (i % 8 ? " " : "\n  "), labelcode(labels[i])
		print "]"
		print ""
		print "/-- The byte size of each directive. -/"
		printf "def sizes : List Nat := ["
		j = 0
		for (i = 0; i < nk; i++) {
			if (kind[i] == "label") s = 0
			else { s = addr[j + 1] - addr[j]; j++ }
			printf "%s%s%d", (i ? "," : ""), (i % 20 ? " " : "\n  "), s
		}
		print "]"
		print ""
		print "end Bbu.BinLayout"
	}' "$tmp/asm" "$tmp/dis" > "$tmp/out"

if [ "${1-}" = --check ]; then
	if ! cmp -s "$tmp/out" "$dir/$out"; then
		diff "$dir/$out" "$tmp/out" | head -20 >&2 || true
		echo "bin_layout: $out is not current; run test/bin_layout.sh" >&2
		exit 1
	fi
	echo "bin_layout: $out is current"
else
	cp "$tmp/out" "$dir/$out"
	echo "bin_layout: wrote $out"
fi
