#!/usr/bin/env bash
# Make BbuKraken/BinLayout.lean, the start address and the byte size of each
# directive of `bbuAsm ++ State.permuteAsm` in c/bbu_harness.
# With --check, do not write the file, but fail if it is not current.
#
# A label has size 0. An instruction has the size of its bytes in the binary plus
# the size of the alignment nops that follow it: the Kraken parser drops `.p2align`,
# so the padding has no directive of its own. This includes the padding between
# the code of build_bottom_up.S and permute.S.
set -euo pipefail
dir=$(cd "$(dirname "$0")/.." && pwd)
out=BbuKraken/BinLayout.lean
bin=$dir/c/bbu_harness
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

make -C "$dir/c" -s bbu_harness
(cd "$dir" && lake build -q BbuKraken.Asm PermuteKraken.Asm Kraken.X64.PrintATT >/dev/null)
(cd "$dir" && lake env lean --run test/BinAsmMain.lean) > "$tmp/asm"
"$dir/test/bin_objdump.sh" "$bin" > "$tmp/dis"

awk -v src="c/bbu_harness" '
	FNR == 1 { file++ }
	# The Kraken program: a label ends with ":", all else is an instruction.
	file == 1 { kind[nk++] = /:$/ ? "label" : "instr"; if (!/:$/) ni++; next }
	# The disassembly: "start ADDR", "stop ADDR", then "ADDR SIZE pad|instr TEXT".
	$1 == "start" { start = $2; next }
	$1 == "stop" { stop = $2; next }
	$3 == "instr" { addr[na++] = strtonum("0x" $1) }
	END {
		if (na != ni) {
			printf "bin_layout: %d instructions in Kraken, %d in %s\n", ni, na, src > "/dev/stderr"
			exit 1
		}
		if (addr[0] != strtonum("0x" start)) {
			print "bin_layout: the first instruction is not at the start" > "/dev/stderr"
			exit 1
		}
		addr[na] = strtonum("0x" stop)
		print "/-! Generated by test/bin_layout.sh from " src ". Do not edit. -/"
		print ""
		print "namespace Bbu.BinLayout"
		print ""
		print "/-- The address of the first directive. -/"
		print "def start : Nat := 0x" start
		print ""
		print "/-- The byte size of each directive. -/"
		printf "def sizes : List Nat := ["
		j = 0
		for (i = 0; i < nk; i++) {
			if (kind[i] == "label") s = 0
			else { s = addr[j + 1] - addr[j]; j++ }
			printf "%s%s%d", (i ? "," : ""), (i % 20 ? " " : "\n  "), s
		}
		print "]"
		print ""
		print "end Bbu.BinLayout"
	}' "$tmp/asm" "$tmp/dis" > "$tmp/out"

if [ "${1-}" = --check ]; then
	if ! cmp -s "$tmp/out" "$dir/$out"; then
		diff "$dir/$out" "$tmp/out" | head -20 >&2 || true
		echo "bin_layout: $out is not current; run test/bin_layout.sh" >&2
		exit 1
	fi
	echo "bin_layout: $out is current"
else
	cp "$tmp/out" "$dir/$out"
	echo "bin_layout: wrote $out"
fi
