#!/usr/bin/env bash
# Make BbuKraken/Sep/Fields.lean: the address of each member of `Emission` in
# c/shuffler/stack/Shuffler.cpp and of each element of its arrays, with the lemmas on these addresses.
# The source of truth is the g++ offsetof and sizeof values (the probe of test/struct_layout.sh).
# With --check, do not write the file, but fail if it is not current.
# BBU_SRC (default c/shuffler/) is the directory of the freestanding sources (for the tests).
set -euo pipefail
dir=$(cd "$(dirname "$0")/.." && pwd)
src=${BBU_SRC:-$dir/c/shuffler}
out=BbuKraken/Sep/Fields.lean
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Each line: the member, its offset, its size, and the size of one element (an array member
# is an `OffsetArray`; the element size of another member is its size).
cat > "$tmp/probe.cpp" <<'CPP'
#include <bit>
#include <compare>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <optional>
#include <type_traits>
#include <utility>
#define private public
#include "stack/Shuffler.cpp"
#define M(f) std::declval<Emission&>().f
#define P(f) std::printf("%s %zu %zu %zu\n", #f, offsetof(Emission, f), sizeof(M(f)), sizeof(M(f)))
#define A(f) std::printf("%s %zu %zu %zu\n", #f, offsetof(Emission, f), sizeof(M(f)), sizeof(M(f).m_elements[0]))
// A reference member has the size of a pointer: sizeof gives the size of the type that it refers to.
#define R(f) static_assert(std::is_reference_v<decltype(Emission::f)>); \
	std::printf("%s %zu %zu %zu\n", #f, offsetof(Emission, f), sizeof(void*), sizeof(void*))
int main()
{
	P(m_target); P(m_targetSize); P(m_spills); P(m_stack.m_data); P(m_stack.m_size); P(m_stack.m_trace);
	P(m_stack.m_traceSize); A(m_mapping.m_destinationOf); A(m_mapping.m_positionOf);
	P(m_pendingGenerations); P(m_blocked.offset); P(m_blocked.excess); R(m_plannedMapping);
	std::printf("size %zu 0 0\n", sizeof(Emission));
}
CPP
# The reference member m_plannedMapping makes Emission a class without standard layout; g++ gives offsetof
# for such a class without a virtual base, but warns.
${CXX:-g++} -std=c++20 -Wno-invalid-offsetof -I "$src" -o "$tmp/probe" "$tmp/probe.cpp"
"$tmp/probe" > "$tmp/offsets"

awk '
function fail(msg) { print "gen_fields: " msg > "/dev/stderr"; bad = 1; exit 1 }
# The Lean name of a member: the parts without `m_`, joined by `_`.
function lname(s,   n, p, i, r) {
	n = split(s, p, ".")
	r = ""
	for (i = 1; i <= n; i++) { sub(/^m_/, "", p[i]); r = r (i > 1 ? "_" : "") p[i] }
	return r
}
$1 == "size" { size = $2; next }
{
	if ($4 != 8) fail($1 ": element size " $4 ", not 8")
	if ($2 != end) fail($1 ": offset " $2 ", not " end)
	if ($3 % 8 != 0) fail($1 ": size " $3)
	k++; cxx[k] = $1; name[k] = lname($1); off[k] = $2; cnt[k] = $3 / 8
	end = $2 + $3
}
# For member `r` and index `i`: `addr` is the address, `offs` the offset from `S`, `hyp` the bound,
# `eq` the rewrite to `S + ofNat offs`. `body` is the address term of the sep atoms.
function arr(r) { return cnt[r] > 1 }
function addr(r, i) { return arr(r) ? name[r] " S " i : name[r] " S" }
function offs(r, i) { return arr(r) ? off[r] " + 8 * " i : off[r] }
function hyp(r, i) { return arr(r) ? " {" i " : Nat} (h" i " : " i " < " cnt[r] ")" : "" }
function eq(r, i) { return arr(r) ? "eq_" name[r] " S " i : "eq_" name[r] " S" }
function body(r) {
	if (arr(r)) return "S + BitVec.ofNat 64 " off[r] " + BitVec.ofNat 64 (8 * i)"
	return off[r] == 0 ? "S" : "S + BitVec.ofNat 64 " off[r]
}
function eqpf(r) {
	if (arr(r)) return "off_arr S " off[r] " i"
	return off[r] == 0 ? "off_zero S" : "rfl"
}
END {
	if (bad) exit 1
	if (end != size) fail("the members end at " end ", sizeof is " size)
	print "module"
	print ""
	print "public import BbuKraken.Sep.Off"
	print "import all BbuKraken.Sep.Off"
	print ""
	print "@[expose] public section"
	print ""
	print "/-! Generated by test/gen_fields.sh from c/shuffler/stack/Shuffler.cpp. Do not edit. -/"
	print ""
	print "namespace Bbu.Fld"
	print ""
	print "/-- The size of `Emission` in bytes. -/"
	print "def SIZE : Nat := " size
	print "theorem SIZE_le : SIZE ≤ 2 ^ 64 := by decide"
	print ""
	print "/-! For each member: the address, the address as `S + offset`, the bytes from `S` (in"
	print "bounds), the address as a number if the struct does not wrap (no overflow), and the fold"
	print "from the address form of the asm after `symexec_norm` (not for the member at offset 0). -/"
	for (r = 1; r <= k; r++) {
		a = arr(r) ? " (i : Nat)" : ""
		print ""
		printf "-- `%s`: byte %d, %d word%s\n", cxx[r], off[r], cnt[r], (arr(r) ? "s" : "")
		printf "def %s (S : BitVec 64)%s : BitVec 64 := %s\n", name[r], a, body(r)
		printf "theorem eq_%s (S : BitVec 64)%s : %s = S + BitVec.ofNat 64 (%s) := %s\n", name[r], a,
			addr(r, "i"), offs(r, "i"), eqpf(r)
		printf "theorem in_%s (S : BitVec 64)%s : (%s - S).toNat + 8 ≤ SIZE := by\n", name[r], hyp(r, "i"),
			addr(r, "i")
		printf "  rw [%s]; exact in_off (show %s + 8 ≤ %d by omega) SIZE_le\n", eq(r, "i"), offs(r, "i"), size
		printf "theorem toNat_%s {S : BitVec 64} (hS : S.toNat + SIZE ≤ 2 ^ 64)%s :\n", name[r], hyp(r, "i")
		printf "    (%s).toNat = S.toNat + (%s) := by\n", addr(r, "i"), offs(r, "i")
		printf "  rw [%s]; exact toNat_off hS (show %s < %d by omega)\n", eq(r, "i"), offs(r, "i"), size
		if (arr(r))
			printf "theorem fold_%s (S x : BitVec 64) : S + x * 8#64 + %d#64 = %s S x.toNat :=\n  fold_arr S x %d\n",
				name[r], off[r], name[r], off[r]
		else if (off[r] > 0)
			printf "theorem fold_%s (S : BitVec 64) : S + %d#64 = %s S := rfl\n", name[r], off[r], name[r]
	}
	print ""
	print "end Bbu.Fld"
}' "$tmp/offsets" > "$tmp/out"

if [ "${1-}" = --check ]; then
	if ! cmp -s "$tmp/out" "$dir/$out"; then
		diff "$dir/$out" "$tmp/out" | head -20 >&2 || true
		echo "gen_fields: $out is not current; run test/gen_fields.sh" >&2
		exit 1
	fi
	echo "gen_fields: $out is current"
else
	cp "$tmp/out" "$dir/$out"
	echo "gen_fields: wrote $out"
fi
