#!/usr/bin/env bash
# Make BbuKraken/StructLayout.lean, the byte offsets of the members of `Emission` in
# c/build_bottom_up.cpp, as g++ lays them out. BbuKraken/Layout.lean proves that its
# word layout agrees with these offsets.
# With --check, do not write the file, but fail if it is not current.
set -euo pipefail
dir=$(cd "$(dirname "$0")/.." && pwd)
out=BbuKraken/StructLayout.lean
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# The members are private. The probe includes the library headers first, so that
# `#define private public` changes only the class of build_bottom_up.cpp.
cat > "$tmp/probe.cpp" <<'CPP'
#include <bit>
#include <compare>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#define private public
#include "build_bottom_up.cpp"
#define P(f) std::printf("%s %zu\n", #f, offsetof(Emission, f))
int main()
{
	P(m_target); P(m_targetSize); P(m_spills); P(m_stack.m_data); P(m_stack.m_size); P(m_stack.m_trace);
	P(m_stack.m_traceSize); P(m_mapping.m_destinationOf); P(m_mapping.m_positionOf);
	P(m_pendingGenerations); P(m_blocked.offset); P(m_blocked.excess);
	std::printf("size %zu\n", sizeof(Emission));
}
CPP
# buildBottomUp calls permute.
${CXX:-g++} -std=c++20 -I "$dir/c" -o "$tmp/probe" "$tmp/probe.cpp" "$dir/c/permute.S"
"$tmp/probe" > "$tmp/offsets"

awk '
	BEGIN {
		print "/-! Generated by test/struct_layout.sh from c/build_bottom_up.cpp. Do not edit. -/"
		print ""
		print "namespace Bbu.StructLayout"
		print ""
		print "/-- The byte offset of each member of `Emission`, and its size. -/"
		print "def offsets : List (String × Nat) := ["
	}
	{ printf "  (\"%s\", %d)%s\n", $1, $2, ($1 == "size" ? "]" : ",") }
	END { print ""; print "end Bbu.StructLayout" }' "$tmp/offsets" > "$tmp/out"

if [ "${1-}" = --check ]; then
	if ! cmp -s "$tmp/out" "$dir/$out"; then
		diff "$dir/$out" "$tmp/out" | head -20 >&2 || true
		echo "struct_layout: $out is not current; run test/struct_layout.sh" >&2
		exit 1
	fi
	echo "struct_layout: $out is current"
else
	cp "$tmp/out" "$dir/$out"
	echo "struct_layout: wrote $out"
fi
